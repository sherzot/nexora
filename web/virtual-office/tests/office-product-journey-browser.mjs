// Run against the guarded synthetic frontend on loopback.
export default async function checkOfficeProductJourney(page, origin) {
  const problems = [];
  page.on('request', (request) => {
    if (new URL(request.url()).origin !== origin) problems.push(request.url());
  });
  page.on('pageerror', (error) => problems.push(error.message));
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const heading = page.locator('#page-title');
  const select = (name) => page.getByRole('button', { name, exact: true });
  const inspector = page.getByRole('region', { name: 'Interaction Inspector' });
  const focusedHeading = (name) => page.waitForFunction((title) => {
    const element = document.activeElement;
    return element.id === 'page-title' && element.textContent.includes(title);
  }, name);

  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(origin + '/#/office');
  await page.locator('.office-webgl canvas').waitFor();
  await select('2D floor plan').press('Enter');
  const ada = page.getByRole('button', { name: /^Select Ada,/ });
  await ada.press('Enter');
  assert(await ada.getAttribute('aria-pressed') === 'true', 'SVG selection must update the Office');
  await page.getByRole('link', { name: 'View agent details' }).press('Enter');
  await focusedHeading('Ada');
  const profileTask = page.locator('.task-detail-list li').first();
  const profileStatus = () => profileTask.locator('.status-label').innerText();
  const fixture = await profileStatus();
  await select('Step forward').press('Enter');
  const active = await profileStatus();
  assert(fixture !== active, 'Fixture task status should give way to active playback');
  await profileTask.getByRole('link').press('Enter');
  await focusedHeading('Task Board');
  assert(await page.locator('.task-card .status-label').innerText() === active, 'Profile and board must agree on task status');
  await page.getByRole('link', { name: 'Return to Office' }).press('Enter');
  await focusedHeading('Virtual Office');
  assert(await page.locator('.agent-inspector h2').first().innerText() === 'Ada', 'Entity inspection must preserve Office agent selection');

  for (let i = 1; i < 24; i++) await select('Step forward').press('Enter');
  await page.getByRole('link', { name: 'Explore collaboration' }).press('Enter');
  await focusedHeading('Collaboration');
  await page.getByRole('button', { name: /Demo Approval/ }).first().press('Enter');
  await inspector.getByRole('link', { name: /^sim-/ }).press('Enter');
  await focusedHeading('Activity Timeline');
  const linkedHash = await page.evaluate(() => location.hash);
  const row = page.locator('[data-collaboration-event]');
  assert(await row.count() === 1, 'Evidence link must resolve one observed interaction');
  const interaction = await row.getAttribute('data-collaboration-event');
  const participant = await inspector.locator('p a[href^="#/agents/"]').first().innerText();
  const taskLink = inspector.locator('a[href^="#/tasks?task="]');
  const task = await taskLink.innerText();
  await taskLink.press('Enter');
  await focusedHeading('Task Board');
  assert(await page.locator('.task-card h3').innerText() === task, 'Interaction task identity changed');
  await page.goBack();
  await focusedHeading('Activity Timeline');
  assert(await row.getAttribute('data-collaboration-event') === interaction, 'Back must restore the evidence route');
  await page.goForward();
  await focusedHeading('Task Board');
  await page.goBack();
  await focusedHeading('Activity Timeline');
  await inspector.getByRole('link', { name: participant, exact: true }).first().press('Enter');
  await focusedHeading(participant);
  await page.getByRole('link', { name: 'Return to Office' }).press('Enter');
  await focusedHeading('Virtual Office');
  assert(await page.locator('[data-office-interaction]').getAttribute('data-office-interaction') === interaction, 'Returning to Office lost the interaction');

  await page.goto(origin + '/' + linkedHash);
  await focusedHeading('Activity Timeline');
  await select('Reset simulation').press('Enter');
  await page.getByText('This interaction is unavailable in the current playback.').waitFor();
  assert(await inspector.count() === 0, 'A reset must clear the stale inspector');
  for (let i = 0; i < 24; i++) await select('Step forward').press('Enter');
  assert(await row.count() === 0 && await inspector.count() === 0, 'Replay must not resurrect the stale link');
  await page.getByRole('link', { name: 'Return to Timeline' }).press('Enter');
  await focusedHeading('Activity Timeline');
  await page.getByLabel('Timeline stream').selectOption('collaboration');
  assert(await row.count() > 1, 'Recovery must expose current observed interactions');

  for (const width of [320, 390]) {
    await page.setViewportSize({ width, height: 844 });
    await page.goto(origin + '/?mobile=' + width + '#/office');
    await page.locator('svg.office-scene').waitFor();
    await ada.press('Enter');
    await page.getByRole('link', { name: 'View agent details' }).press('Enter');
    await focusedHeading('Ada');
    await profileTask.getByRole('link').press('Enter');
    await focusedHeading('Task Board');
    await page.getByRole('link', { name: 'Return to Office' }).press('Enter');
    await focusedHeading('Virtual Office');
    await page.locator('svg.office-scene').waitFor();
    assert(await ada.getAttribute('aria-pressed') === 'true', 'Mobile return lost the SVG selection');
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile Office overflow');
    await page.goto(origin + '/' + linkedHash);
    await page.getByRole('link', { name: 'Return to Timeline' }).waitFor();
  }
  // C23: outcomes are projections of the existing playback, including reset and scenario lifetime.
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(origin + '/#/office');
  await focusedHeading('Virtual Office');
  const results = page.getByRole('region', { name: 'Playback results', exact: true });
  const recent = page.getByRole('region', { name: 'Recent office activity', exact: true });
  const outcomes = page.getByRole('region', { name: 'Playback task outcomes', exact: true });
  const currentTask = page.getByRole('region', { name: 'Selected agent current task', exact: true });
  const progress = page.getByRole('progressbar', { name: 'Demo playback progress', exact: true });
  const metric = (label) => results.locator('dl > div').filter({ has: page.getByText(label, { exact: true }) }).locator('dd');
  const controls = page.getByRole('region', { name: 'Synthetic simulation controls', exact: true });
  await select('Reset simulation').press('Enter');
  assert((await results.innerText()).includes('No task results have been observed.'), 'Inactive fixture statuses are not playback results');
  assert(await metric('Observed events').innerText() === '0', 'Reset must clear observed events');
  assert(await currentTask.count() === 0, 'Inactive playback has no current assignment');
  assert(await progress.getAttribute('value') === '0' && await progress.getAttribute('max') === '32', 'Progress must use the model horizon');
  await page.getByRole('combobox', { name: 'Scenario', exact: true }).selectOption('collaboration');
  for (let step = 0; step < 8; step++) await select('Step forward').press('Enter');
  assert(await metric('Moving agents').innerText() === '8 / 8', 'All agents must be moving at this observed collaboration step');
  assert(await metric('On-task agents').innerText() === '0 / 8', 'Moving agents are not counted as working');
  assert(await progress.getAttribute('value') === '8', 'Step must update progress');
  const eventCount = Number(await metric('Observed events').innerText());
  assert(eventCount === 8, 'One movement event per agent must be observed');
  assert(await recent.getByRole('button').count() === 5, 'Recent activity list must be bounded');
  const eventButton = recent.getByRole('button').first();
  const eventLabel = await eventButton.getAttribute('aria-label');
  await eventButton.press('Enter');
  assert(await page.locator('#office-agent-inspector').evaluate((el) => el === document.activeElement && el.matches(':focus-visible')), 'Activity selection must focus the inspector visibly');
  const selectedName = await page.locator('.agent-inspector h2').first().innerText();
  assert(eventLabel.includes(selectedName), 'Recent event must select its actual participant');
  const currentTaskName = await currentTask.getByRole('link').innerText();
  await currentTask.getByRole('link').press('Enter');
  await focusedHeading('Task Board');
  assert(await page.locator('.task-card h3').innerText() === currentTaskName, 'Current task must link to the same board task');
  await page.getByRole('link', { name: 'Return to Office' }).press('Enter');
  await focusedHeading('Virtual Office');
  for (let step = 8; step < 32; step++) await select('Step forward').press('Enter');
  assert((await controls.innerText()).includes('finished'), 'Existing playback must reach its terminal state');
  assert((await results.innerText()).includes('This synthetic scenario is finished.'), 'Completion must show a clear outcome');
  const taskCount = await outcomes.getByRole('listitem').count();
  assert(await metric('Completed demo tasks').innerText() === `${taskCount} / ${taskCount}`, 'Completed count must use unique scenario tasks, not all fixture tasks');
  const terminalOutcomes = await outcomes.getByRole('listitem').allTextContents();
  assert(terminalOutcomes.every((text) => text.includes('Done')), 'Every assigned scenario task must be complete');
  await results.getByRole('link', { name: 'Open analytics & reports →', exact: true }).press('Enter');
  await focusedHeading('Simulation Analytics');
  await page.goBack();
  await focusedHeading('Virtual Office');
  assert((await results.innerText()).includes('This synthetic scenario is finished.'), 'Navigation must retain playback outcomes');
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Mission Planning', exact: true }).press('Enter');
  await focusedHeading('Mission Planning');
  assert(await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Mission Planning', exact: true }).getAttribute('aria-current') === 'page', 'Mission navigation must reflect the actual route');
  await page.getByRole('link', { name: 'Return to Office', exact: true }).press('Enter');
  await focusedHeading('Virtual Office');
  assert(await progress.getAttribute('value') === '32', 'Planning navigation must not execute or reset Office playback');
  await page.getByRole('combobox', { name: 'Scenario', exact: true }).selectOption('review');
  assert(await metric('Observed events').innerText() === '0', 'Scenario replacement must clear old outcomes');
  assert(await recent.getByRole('button').count() === 0, 'Scenario replacement must clear old activity');
  await select('Start').press('Enter');
  await page.waitForFunction(() => Number(document.querySelector('progress[aria-label="Demo playback progress"]')?.value) > 0);
  await select('Pause').press('Enter');
  const pausedAt = await progress.getAttribute('value');
  await page.waitForTimeout(650);
  assert(await progress.getAttribute('value') === pausedAt, 'Pause must stop outcome progress');
  await select('Resume').press('Enter');
  await page.waitForFunction((tick) => Number(document.querySelector('progress[aria-label="Demo playback progress"]')?.value) > tick, Number(pausedAt));
  await select('Pause').press('Enter');
  await select('Reset simulation').press('Enter');
  assert(await progress.getAttribute('value') === '0', 'Reset must restore the initial progress');

  assert(problems.length === 0, JSON.stringify(problems));
  return { playbackOutcomes: 'PASS', observedActivity: 'PASS', missionNavigation: 'PASS', keyboard: 'PASS', taskStatus: 'PASS', identity: 'PASS', history: 'PASS', staleLink: 'PASS', mobileWidths: [320, 390] };
}
