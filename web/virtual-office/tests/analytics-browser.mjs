/** Existing approved Playwright tooling supplies Page; no dependency added. */
export default async function checkAnalytics(page, origin = 'http://127.0.0.1:4194') {
  page.setDefaultTimeout(10000); await page.bringToFront();
  const assert = (value, label) => { if (!value) throw new Error(label); };
  await page.addInitScript(() => {
    window.__reportUrls = new Set();
    const create = URL.createObjectURL, revoke = URL.revokeObjectURL;
    URL.createObjectURL = function (blob) { const url = create.call(this, blob); window.__reportUrls.add(url); return url; };
    URL.revokeObjectURL = function (url) { window.__reportUrls.delete(url); return revoke.call(this, url); };
  });
  const external = [], errors = [];
  page.on('request', (r) => { if (new URL(r.url()).origin !== origin) external.push(r.url()); });
  page.on('pageerror', (e) => errors.push(e.message));
  await page.emulateMedia({ reducedMotion: 'reduce' }); await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`${origin}/#/analytics`); await page.getByRole('heading', { name: 'Simulation Analytics', exact: true }).waitFor();
  assert(await page.locator('canvas').count() === 0, 'Analytics owns no WebGL canvas');
  assert(await page.evaluate(() => !performance.getEntriesByType('resource').some((r) => r.name.includes('/renderer-'))), 'Analytics does not load renderer chunk');
  const clock = () => page.locator('.simulation-controls time').textContent();
  const initialTime = await clock();
  await page.getByRole('combobox', { name: 'Comparison horizon', exact: true }).selectOption('32');
  assert(await clock() === initialTime, 'Independent comparison does not advance live simulation');
  assert(await page.locator('.analytics-comparison article').count() === 3, 'Three scenario comparisons');
  await page.getByRole('combobox', { name: 'Analytics agent', exact: true }).selectOption('demo-agent-ada');
  assert(await page.locator('.analytics-table tbody tr').count() === 1, 'Agent filter applies to metrics');
  for (let i = 0; i < 16; i++) await page.getByRole('button', { name: 'Step forward', exact: true }).click();
  assert(await clock() === 'T+00:08.000', 'Metrics follow authoritative virtual clock');
  const download = async (format) => {
    const pending = page.waitForEvent('download'); await page.getByRole('button', { name: `Export ${format}`, exact: true }).click();
    const file = await pending, stream = await file.createReadStream(), chunks = [];
    for await (const chunk of stream) chunks.push(Buffer.from(chunk));
    return Buffer.concat(chunks);
  };
  const json1 = await download('JSON'), json2 = await download('JSON');
  const csv1 = await download('CSV'), csv2 = await download('CSV');
  assert(json1.equals(json2) && csv1.equals(csv2), 'Repeated downloads must be byte-identical');
  assert(await page.evaluate(() => window.__reportUrls.size) === 1, 'At most one report URL retained');
  const report = JSON.parse(json1.toString());
  assert(report.schemaVersion === 1 && report.seed === 42 && report.horizon.tick === 16 && report.metrics.agents.length === 1, 'JSON report metadata and scope');
  assert(report.comparison.length === 3 && report.comparison.every((m) => m.tick === 32 && m.seed === 42), 'Comparison uses explicit common horizon');
  assert(csv1.toString().includes('scope_agent_ids') && csv1.toString().includes('comparison_zone'), 'CSV metadata and comparison zones');
  await page.evaluate(() => { location.hash = '/office'; });
  await page.locator('.agent-select').filter({ hasText: 'Theo' }).click();
  await page.evaluate(() => { location.hash = '/activity'; }); await page.waitForSelector('[data-simulation-event]');
  assert(await page.evaluate(() => window.__reportUrls.size) === 0, 'Report URL released when analytics unmounts');
  const before = await page.locator('[data-simulation-event]').count();
  await page.getByRole('combobox', { name: 'Timeline agent', exact: true }).selectOption('demo-agent-ada');
  await page.getByRole('combobox', { name: 'Activity type', exact: true }).selectOption('moving');
  await page.getByRole('combobox', { name: 'Timeline zone', exact: true }).selectOption('demo-room-studio');
  await page.getByRole('spinbutton', { name: 'From tick (500 ms)', exact: true }).fill('1');
  await page.getByRole('spinbutton', { name: 'Through tick (inclusive)', exact: true }).fill('4');
  await page.getByRole('searchbox', { name: 'Search synthetic events', exact: true }).fill('Ada');
  assert(await page.locator('[data-simulation-event]').count() === 1, 'Combined timeline filters');
  await page.getByText('Event details', { exact: true }).click();
  assert((await page.locator('.analytics-event-id').textContent()).startsWith('sim-day-42-'), 'Event details expose deterministic identity');
  await page.getByRole('button', { name: 'Inspect Ada', exact: true }).click();
  assert(await page.locator('.agent-inspector h2').textContent() === 'Ada', 'Timeline selection stays synchronized');
  await page.evaluate(() => { location.hash = '/activity'; }); await page.getByRole('button', { name: 'Clear simulation filters', exact: true }).click();
  assert(await page.locator('[data-simulation-event]').count() === before, 'Filtering never mutates history');
  await page.getByRole('spinbutton', { name: 'From tick (500 ms)', exact: true }).fill('32');
  await page.getByRole('spinbutton', { name: 'Through tick (inclusive)', exact: true }).fill('0');
  assert(await page.getByRole('alert').count() === 1 && await page.locator('[data-simulation-event]').count() === 0, 'Inverted ranges are explicit and empty');
  await page.getByRole('combobox', { name: 'Scenario', exact: true }).selectOption('review');
  assert(await clock() === 'T+00:00.000', 'Scenario switch resets shared clock and derived views');
  await page.evaluate(() => { location.hash = '/analytics'; });
  assert(await page.locator('.analytics-table tbody tr').count() === 8, 'Scenario switch clears obsolete agent scope');
  await page.evaluate(() => { location.hash = '/workspace'; }); await page.getByRole('combobox', { name: /Theme/ }).selectOption('dark');
  await page.evaluate(() => { location.hash = '/analytics'; }); assert(await page.locator('.app-shell').getAttribute('data-theme') === 'dark', 'Dark analytics theme');
  await page.getByRole('button', { name: 'Export JSON', exact: true }).focus(); assert(await page.getByRole('button', { name: 'Export JSON', exact: true }).evaluate((e) => e === document.activeElement), 'Keyboard-focusable report controls');
  await page.setViewportSize({ width: 390, height: 844 }); await page.reload(); await page.getByRole('heading', { name: 'Simulation Analytics', exact: true }).waitFor();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No analytics mobile page overflow');
  assert(await page.locator('canvas').count() === 0, 'Mobile analytics has no renderer loop');
  await page.getByRole('button', { name: 'Reset simulation', exact: true }).click(); assert(await clock() === 'T+00:00.000', 'Reset remains available from analytics');
  assert(!external.length && !errors.length, 'No external requests or uncaught errors');
  return { comparison: 3, agentFiltering: 'PASS', timelineFilters: 'PASS', eventSelection: 'PASS', downloadDeterminism: 'PASS', jsonBytes: json1.length, csvBytes: csv1.length, resetSwitch: 'PASS', darkMobileReducedMotion: 'PASS', noRenderer: 'PASS', reportCleanup: 'PASS', external, errors };
}
