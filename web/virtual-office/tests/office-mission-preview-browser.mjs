// Run against the guarded synthetic frontend on loopback.
export default async function checkMissionPreview(page, origin) {
  const problems = [];
  page.on('request', (request) => {
    if (new URL(request.url()).origin !== origin) problems.push(request.url());
  });
  page.on('pageerror', (error) => problems.push(error.message));
  const assert = (ok, reason) => { if (!ok) throw new Error(reason); };
  const button = (name) => page.getByRole('button', { name, exact: true });
  const link = (name) => page.getByRole('link', { name, exact: true });
  const heading = (title) => page.waitForFunction((name) =>
    document.activeElement?.id === 'page-title' && document.activeElement.textContent.includes(name), title);
  const focus = (control) => control.evaluate((node) => node === document.activeElement && node.matches(':focus-visible'));
  const tasks = page.getByRole('group', { name: 'Select mission tasks' }).getByRole('checkbox');
  const region = page.getByRole('region', { name: 'Mission preview', exact: true });
  const events = region.getByRole('list', { name: 'Hypothetical mission events' }).getByRole('listitem');
  const step = button('Step preview');
  const first = 'Shape the workspace layout';
  const second = 'Map rooms to team context';
  const assignment = (task) => page.getByRole('combobox', { name: 'Proposed agent for ' + task, exact: true });
  const assign = async () => {
    await assignment(first).selectOption('demo-agent-ada');
    await assignment(second).selectOption('demo-agent-noah');
  };
  const clock = () => page.locator('.simulation-controls time').innerText();
  const assumption = (title) => page.getByRole('checkbox', { name: new RegExp('^Assume complete: ' + title) });

  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(origin + '/#/office');
  await button('2D floor plan').press('Enter');
  await page.getByRole('button', { name: /^Select Leo,/ }).press('Enter');
  await link('Plan a mission').press('Enter');
  await heading('Mission Planning');
  await tasks.nth(0).press('Space');
  await tasks.nth(1).press('Space');
  await tasks.nth(2).press('Space');
  await button('Capture Plan A').press('Enter');
  await tasks.nth(2).press('Space');
  const dependent = page.getByLabel('Dependent task');
  const required = page.getByLabel('Required task');
  await dependent.selectOption('demo-task-map');
  await required.selectOption('demo-task-layout');
  await button('Add prerequisite').press('Enter');
  const start = button('Start preview');
  if (await start.isEnabled()) await start.press('Enter');
  assert(await step.count() === 0 || await step.isDisabled(), 'A task without a proposed agent must block simulated work');
  await assign();
  const initialClock = await clock();
  await start.press('Enter');
  await step.waitFor();
  assert(await events.count() === 0, 'Preview must start at step zero');
  const initial = await region.innerText();
  assert(initial.includes('Ready') && initial.includes('Blocked'), 'Preview must expose readiness and unmet prerequisites');

  await step.press('Enter');
  assert(await events.count() === 1 && (await events.first().innerText()).includes(first), 'First ready task must start with exactly one event');
  assert((await events.first().innerText()).includes('Ada'), 'First task event must name its proposed agent');
  await step.press('Enter');
  assert(await events.count() === 2 && (await events.nth(1).innerText()).includes(first), 'Active prerequisite must complete before its dependent starts');
  await step.press('Enter');
  assert(await events.count() === 3 && (await events.nth(2).innerText()).includes(second), 'Completion must make the dependent eligible to start');
  await step.press('Enter');
  assert(await events.count() === 4 && (await events.nth(3).innerText()).includes('Noah'), 'Terminal mission must retain both participant identities');
  assert(await step.isDisabled(), 'Terminal preview must prevent further transitions');
  const terminal = await events.allTextContents();
  assert(terminal.every((event, index) => event.includes(String(index + 1)) && /hypothetical/i.test(event)), 'Events must expose step number and hypothetical provenance');
  assert(await clock() === initialClock, 'Mission preview must not advance playback');

  await assumption('Trace keyboard navigation').press('Space');
  assert(JSON.stringify(await events.allTextContents()) === JSON.stringify(terminal), 'Plan A-only edits must preserve the preview');
  await button('Add prerequisite').press('Enter');
  assert(JSON.stringify(await events.allTextContents()) === JSON.stringify(terminal), 'Rejected edits must preserve the preview');
  await button('Step forward').press('Enter');
  assert(await clock() !== initialClock, 'Playback must remain independently controllable');
  await page.getByRole('combobox', { name: 'Scenario', exact: true }).selectOption('review');
  await button('Reset simulation').press('Enter');
  assert(JSON.stringify(await events.allTextContents()) === JSON.stringify(terminal), 'Playback step, scenario switch, and reset must preserve the preview');

  await button('Reset preview').press('Enter');
  assert(await events.count() === 0 && await focus(step), 'Reset preview must clear events and restore visible focus to Step preview');
  assert(await assignment(first).inputValue() === 'demo-agent-ada', 'Reset preview must retain the editable assignment');
  for (let i = 0; i < 4; i++) await step.press('Enter');
  assert(JSON.stringify(await events.allTextContents()) === JSON.stringify(terminal), 'Reset and replay must produce identical rendering');
  await assignment(first).selectOption('demo-agent-leo');
  assert(await events.count() === 0, 'Successful assignment edit must invalidate the captured preview');
  await start.press('Enter');
  await step.press('Enter');
  assert((await events.first().innerText()).includes('Leo'), 'A replacement preview must use the new assignment');
  await assumption(first).press('Space');
  assert(await events.count() === 0, 'Changing a Plan B completion assumption must invalidate the preview');
  await start.press('Enter');
  await step.press('Enter');
  assert(await events.count() === 1 && (await events.first().innerText()).includes(second), 'Assumed prerequisite completion must emit no event and unblock the dependent');
  await page.getByRole('button', { name: /^Remove prerequisite:/ }).press('Enter');
  assert(await events.count() === 0 && await focus(dependent), 'Removing a prerequisite must invalidate preview and recover keyboard focus');
  await start.press('Enter');
  await step.press('Enter');
  await tasks.first().press('Space');
  assert(await events.count() === 0 && await assignment(first).count() === 0, 'Removing a task must invalidate preview and remove its assignment');
  await tasks.first().press('Space');
  assert(await assignment(first).inputValue() === '', 'A re-added task must not inherit its removed assignment');

  await button('Reset mission').press('Enter');
  assert(await focus(tasks.first()) && await assignment(first).count() === 0 && await events.count() === 0, 'Reset mission must clear inputs and restore visible focus');
  await tasks.first().press('Space');
  await link('Return to Office').press('Enter');
  await heading('Virtual Office');
  await page.goBack();
  await heading('Mission Planning');
  assert(!(await tasks.first().isChecked()), 'Returning through history must start a fresh draft');
  await page.goForward();
  await heading('Virtual Office');
  await button('2D floor plan').press('Enter');
  await page.getByRole('button', { name: /^Select Leo,/ }).press('Enter');
  await link('Plan a mission').press('Enter');
  await link('Return to Office').press('Enter');
  await heading('Virtual Office');
  assert((await page.locator('.agent-inspector h2').first().innerText()) === 'Leo', 'Mission route must preserve selection outside playback resets');

  // C24: the shared renderer displays captured mission states without consuming playback.
  await page.goto(origin + '/#/workspace');
  await page.getByRole('combobox', { name: /^Theme/ }).selectOption('dark');
  await page.getByRole('checkbox', { name: /^Reduce motion/ }).check();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto(origin + '/#/mission');
  await heading('Mission Planning');
  await button('Load sample mission').press('Enter');
  await start.press('Enter');
  const scene = page.getByRole('region', { name: 'Mission office preview', exact: true });
  const selectedTasks = scene.getByRole('region', { name: 'Selected mission agent tasks', exact: true });
  const missionCanvas = scene.locator('.office-webgl canvas');
  await missionCanvas.waitFor();
  assert(await page.locator('.app-shell').getAttribute('data-theme') === 'dark', 'Mission must retain the selected dark theme');
  assert(await page.locator('.app-shell').getAttribute('data-reduced-motion') === 'true', 'Mission must retain reduced motion');
  const selectedStatus = (name) => scene.getByRole('button', { name: 'Select mission ' + name, exact: true });
  assert((await selectedStatus('Ada').innerText()).includes('Ready'), 'Ada must project the actual ready task');
  assert((await selectedStatus('Noah').innerText()).includes('Blocked'), 'Noah must project the captured prerequisite blocker');
  assert((await selectedStatus('Owen').innerText()).includes('Not assigned'), 'Unassigned fixture agents must remain explicit');
  await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  const sceneImage = async () => {
    await missionCanvas.scrollIntoViewIfNeeded();
    const box = await missionCanvas.boundingBox();
    assert(box, 'Mission canvas must have visible bounds');
    // Normalize fractional clipping edges and exclude the HTML caption: compare actual WebGL pixels.
    return page.screenshot({ clip: { x: Math.ceil(box.x) + 1, y: Math.ceil(box.y) + 1,
      width: Math.floor(box.width) - 2, height: Math.floor(box.height * 0.72) } });
  };
  const readyImage = await sceneImage();
  const officeClock = await clock();
  await step.press('Enter');
  assert((await selectedTasks.innerText()).includes('Active'), 'Mission inspector must match the active preview task');
  assert((await selectedStatus('Ada').innerText()).includes('Active'), 'Mission agent badge must match the preview');
  await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  const activeImage = await sceneImage();
  assert(!readyImage.equals(activeImage), 'Actual WebGL rendering must change for the task status');
  assert(await clock() === officeClock, 'Mission steps cannot drive the Office clock');
  const activeTasks = await selectedTasks.innerText();
  await button('Step forward').press('Enter');
  await page.getByRole('combobox', { name: 'Scenario', exact: true }).selectOption('collaboration');
  await button('Reset simulation').press('Enter');
  assert(await selectedTasks.innerText() === activeTasks, 'Office playback cannot replace captured mission state');
  await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  assert(activeImage.equals(await sceneImage()), 'Office reset must not recolor or move the Mission scene');
  await selectedStatus('Noah').press('Enter');
  assert((await selectedTasks.innerText()).includes('Requires: ' + first), 'Selection must expose the actual unmet prerequisite');
  assert(await focus(selectedStatus('Noah')), 'HTML mission selection must retain visible keyboard focus');
  await missionCanvas.evaluate((canvas) => canvas.dispatchEvent(new Event('webglcontextlost', { cancelable: true })));
  await scene.locator('svg.office-scene').waitFor();
  assert((await selectedTasks.innerText()).includes('Blocked'), 'WebGL failure must preserve the mission inspector');
  assert((await scene.getByRole('button', { name: /^Select Noah,/ }).getAttribute('aria-label')).includes('Blocked'), 'SVG fallback must expose the same mission status');
  await button('3D office').press('Enter');
  await missionCanvas.waitFor();
  assert((await selectedTasks.innerText()).includes('Blocked'), 'Renderer remount must retain selection and state');
  await button('Reset preview').press('Enter');
  for (let count = 0; count < 6; count++) await step.press('Enter');
  assert((await selectedStatus('Noah').innerText()).includes('Completed'), 'Terminal projection must use completed task states');
  await assumption(first).press('Space');
  assert(await scene.count() === 0 && await missionCanvas.count() === 0, 'Successful edit must dispose the obsolete scene');
  await assignment(first).selectOption('');
  await start.press('Enter');
  assert((await scene.getByRole('region', { name: 'Mission tasks without an assigned agent' }).innerText()).includes('Assumed complete'), 'An assumed task without an agent stays visible without invented attribution');
  await button('Reset mission').press('Enter');
  assert(await scene.count() === 0, 'Mission reset must release its scene');

  // C25: presentation pacing consumes only the existing captured transition function.
  await button('Load sample mission').press('Enter');
  await start.press('Enter');
  // Preserve the existing macOS WebKit full-keyboard-navigation convention.
  const nextFocus = process.platform === 'darwin' && page.context().browser()?.browserType().name() === 'webkit' ? 'Alt+Tab' : 'Tab';
  const playbackStatus = page.getByRole('status', { name: 'Mission playback status' });
  const speed = page.getByRole('combobox', { name: 'Preview speed', exact: true });
  const follow = page.getByRole('checkbox', { name: 'Follow active agent', exact: true });
  const waitEvents = (count) => page.waitForFunction((n) =>
    document.querySelectorAll('ol[aria-label="Hypothetical mission events"] > li').length === n, count, { timeout: 10000 });
  assert(await events.count() === 0 && (await playbackStatus.innerText()).includes('idle'), 'Capture cannot start autoplay');
  await speed.selectOption('4');
  await follow.check();
  const autoplayOfficeClock = await clock();
  await button('Play preview').press('Enter');
  assert(await step.getAttribute('aria-disabled') === 'true', 'Manual step cannot race playback');
  await page.waitForFunction(() => document.querySelectorAll('ol[aria-label="Hypothetical mission events"] > li').length > 0, undefined, { timeout: 10000 });
  await page.keyboard.press(nextFocus);
  assert(await focus(button('Pause preview')), 'Tab from Play must reach the visible Pause control');
  await page.keyboard.press('Enter');
  const pausedEvents = await events.count();
  assert(pausedEvents > 0 && pausedEvents < 6, 'Pause must interrupt a bounded playback');
  assert(await focus(button('Pause preview')), 'Paused control must retain visible keyboard focus');
  await page.waitForTimeout(600);
  assert(await events.count() === pausedEvents, 'Pause must cancel pending transitions');
  await page.keyboard.press(nextFocus);
  assert(await focus(button('Resume preview')), 'Tab from Pause must reach Resume');
  await page.keyboard.press('Enter');
  await waitEvents(6);
  assert((await playbackStatus.innerText()).includes('finished'), 'Autoplay must stop at terminal state');
  assert(await clock() === autoplayOfficeClock, 'Autoplay cannot advance the Office clock');
  assert(await selectedStatus('Iris').getAttribute('aria-pressed') === 'true', 'Follow must select the latest active assignee');
  const automaticTrace = await events.allTextContents();
  await button('Reset preview').press('Enter');
  assert(await events.count() === 0 && await focus(step), 'Reset must restore step-zero state and visible focus');
  await button('Play preview').press('Enter');
  await waitEvents(6);
  assert(JSON.stringify(await events.allTextContents()) === JSON.stringify(automaticTrace), 'Reset and Play must reproduce the exact captured trace');

  await button('Reset preview').press('Enter');
  await selectedStatus('Noah').press('Enter');
  assert(!(await follow.isChecked()), 'Manual agent selection must disable following');
  await step.press('Enter');
  assert(await selectedStatus('Noah').getAttribute('aria-pressed') === 'true', 'Manual selection must survive a transition');
  await button('Resume preview').press('Enter');
  await start.press('Enter');
  await page.waitForTimeout(600);
  assert(await events.count() === 0 && (await playbackStatus.innerText()).includes('idle'), 'Recapture must reject callbacks from the previous capture');
  await button('Play preview').press('Enter');
  // Controlled visibility event verifies the component handler; fake-clock tests verify stale callback rejection.
  await page.evaluate(() => {
    Object.defineProperty(document, 'hidden', { configurable: true, get: () => true });
    document.dispatchEvent(new Event('visibilitychange'));
  });
  await page.waitForTimeout(600);
  assert((await playbackStatus.innerText()).includes('paused') && await events.count() === 0, 'Hidden-tab event must pause without advancing');
  await button('Resume preview').press('Enter');
  assert((await playbackStatus.innerText()).includes('paused'), 'Hidden document cannot resume playback');
  await page.evaluate(() => { delete document.hidden; document.dispatchEvent(new Event('visibilitychange')); });
  assert((await playbackStatus.innerText()).includes('paused'), 'Returning to visibility must require explicit Resume');
  await button('Resume preview').press('Enter');
  await assignment(first).selectOption('demo-agent-leo');
  await page.waitForTimeout(600);
  assert(await scene.count() === 0 && await events.count() === 0, 'Draft edit must cancel playback and remove obsolete evidence');
  await start.press('Enter');
  assert(await events.count() === 0, 'Edited capture must remain idle');
  await button('Play preview').press('Enter');
  await link('Return to Office').press('Enter');
  await heading('Virtual Office');
  await page.waitForTimeout(600);
  await link('Plan a mission').press('Enter');
  await heading('Mission Planning');
  assert(await scene.count() === 0 && await events.count() === 0, 'Route exit must cancel and release captured playback');

  for (const width of [320, 390]) {
    await page.setViewportSize({ width, height: 844 });
    await page.goto(origin + '/?mission-preview=' + width + '#/office');
    await page.locator('svg.office-scene').waitFor();
    await link('Plan a mission').press('Enter');
    await heading('Mission Planning');
    await tasks.first().press('Space');
    await assignment(first).selectOption('demo-agent-ada');
    await start.press('Enter');
    await step.press('Enter');
    await scene.locator('svg.office-scene').waitFor();
    assert((await selectedStatus('Ada').innerText()).includes('Active'), 'Mobile SVG must use the same active task projection');
    assert(await events.count() === 1 && await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile preview must fit and expose events');
    const mobileControls = page.getByRole('group', { name: 'Mission playback controls' });
    assert(await mobileControls.locator('button, select').evaluateAll((nodes) => nodes.every((node) => node.getBoundingClientRect().height >= 44)), 'Mobile playback controls must have usable touch targets');
    await button('Reset preview').press('Enter');
    await page.getByRole('combobox', { name: 'Preview speed', exact: true }).selectOption('4');
    await button('Play preview').press('Enter');
    await waitEvents(2);
    assert((await selectedStatus('Ada').innerText()).includes('Completed'), 'Mobile autoplay must update SVG mission status');
    await page.reload();
    await heading('Mission Planning');
    assert(!(await tasks.first().isChecked()) && await events.count() === 0, 'Reload must end the local preview session');
  }

  assert(problems.length === 0, JSON.stringify(problems));
  return { autoplay: 'PASS', pauseResume: 'PASS', deterministicReplay: 'PASS', followAgent: 'PASS', staleCallbacks: 'PASS', controlledVisibilityPause: 'PASS', missionScene: 'PASS', webglStatus: 'PASS', sceneIsolation: 'PASS', contextLossFallback: 'PASS', assignment: 'PASS', prerequisites: 'PASS', replay: 'PASS', isolation: 'PASS', invalidation: 'PASS', focus: 'PASS', history: 'PASS', widths: [320, 390], problems };
}
